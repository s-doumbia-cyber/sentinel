/**
 * Migrates data written by the legacy JavaScript backend into the Sentinel v1
 * data model. DRY RUN by default: nothing is written unless --apply is given.
 *
 *   npm run migrate:legacy -w @sentinel/api              # report only
 *   npm run migrate:legacy -w @sentinel/api -- --apply   # perform the migration
 *
 * What --apply does (idempotent: only touches documents without an orgId):
 *  - creates the org "Legacy workspace" and a membership for every legacy user
 *    (oldest Admin -> Owner, Admin -> Admin, Analyst -> Analyst, Viewer -> Viewer);
 *  - imported flows (those with a datasetId): sets orgId, sourceKind=IMPORTED,
 *    featureSchema=cicids2017-v1, recomputes groundTruthLabel and timestamp
 *    from the stored raw CSV row with the corrected normaliser and day/month
 *    parsing, extracts model features, marks them pending (unscored); the
 *    legacy label/prediction/severity/isAttack are moved under `legacy.*`;
 *  - flows WITHOUT a datasetId came from the random `seed.js` generator: they
 *    are fabricated and are NOT migrated (they stay invisible to the new API);
 *  - datasets and incidents get the orgId; incidents that the old backend
 *    auto-generated with invented assignees are flagged legacyAutoGenerated.
 * Nothing is deleted. The `raw` CSV row is kept unless --drop-raw is given.
 */
import "dotenv/config";
import mongoose from "mongoose";
import { applyLegacyMigration, planLegacyMigration } from "../modules/migration/legacy.js";

const APPLY = process.argv.includes("--apply");
const DROP_RAW = process.argv.includes("--drop-raw");

async function main() {
  const uri = process.env.MONGO_URI;
  if (!uri) throw new Error("MONGO_URI is not set (apps/api/.env)");
  await mongoose.connect(uri);
  const db = mongoose.connection.db;
  if (!db) throw new Error("No database handle");

  console.log(`\nSentinel legacy migration: ${APPLY ? "APPLY" : "DRY RUN (no changes)"}\n`);
  const report = await planLegacyMigration(db);
  console.table(report);
  if (!APPLY) {
    console.log("\nRe-run with --apply to perform these changes. Back up the database first (mongodump).");
    await mongoose.disconnect();
    return;
  }
  const result = await applyLegacyMigration(db, {
    dropRaw: DROP_RAW,
    onProgress: (n) => process.stdout.write(`\rMigrated ${n} flows...`),
  });
  console.log("");
  console.table({ ...result, orgId: String(result.orgId) });
  console.log(`${report.seededFlowsNotMigrated} random seed flows were left untouched and are not visible in Sentinel.`);
  console.log("Next: start the ML service, activate a model in Models, then run scoring.");
  await mongoose.disconnect();
}

main().catch(async (err: unknown) => {
  console.error(`Migration failed: ${err instanceof Error ? err.message : String(err)}`);
  await mongoose.disconnect().catch(() => undefined);
  process.exit(1);
});
