import type { Types } from "mongoose";
import {
  INCIDENT_STATUSES,
  PRIORITIES,
  createIncidentBodySchema,
  incidentNoteBodySchema,
  objectIdSchema,
  updateIncidentBodySchema,
} from "@sentinel/shared";
import { z } from "zod";
import type { AppConfig } from "../../config/index.js";
import { AppError } from "../../lib/errors.js";
import { ah, authOf, parsed, validate } from "../../lib/http.js";
import { PolicyRouter } from "../../lib/routes.js";
import { Membership, User } from "../../models/identity.js";
import { Incident, type IncidentDoc } from "../../models/tenant.js";
import { auditFromRequest } from "../audit/audit.service.js";

const idParams = z.object({ id: objectIdSchema });
const listQuery = z.object({
  status: z.enum(INCIDENT_STATUSES).optional(),
  priority: z.enum(PRIORITIES).optional(),
  limit: z.coerce.number().int().min(1).max(500).default(200),
});

async function userNames(ids: (Types.ObjectId | null | undefined)[]): Promise<Map<string, string>> {
  const unique = [...new Set(ids.filter(Boolean).map(String))];
  const users = unique.length ? await User.find({ _id: { $in: unique } }).select("name").lean() : [];
  return new Map(users.map((u) => [String(u._id), u.name]));
}

function toIncidentResponse(i: IncidentDoc, names: Map<string, string>) {
  const ts = i as unknown as { createdAt: Date; updatedAt: Date };
  return {
    id: String(i._id),
    title: i.title,
    description: i.description,
    attackType: i.attackType,
    status: i.status,
    priority: i.priority,
    severity: i.severity,
    sourceIp: i.sourceIp ?? null,
    assignee: i.assigneeId ? { id: String(i.assigneeId), name: names.get(String(i.assigneeId)) ?? "Former member" } : null,
    legacyAutoGenerated: i.legacyAutoGenerated ?? false,
    notes: (i.notes ?? []).map((n) => ({
      authorId: n.authorId ? String(n.authorId) : null,
      authorName: n.authorId ? (names.get(String(n.authorId)) ?? "Former member") : null,
      text: n.text,
      createdAt: n.createdAt,
    })),
    createdAt: ts.createdAt,
    updatedAt: ts.updatedAt,
  };
}

async function respondWith(i: IncidentDoc) {
  const names = await userNames([i.assigneeId, ...(i.notes ?? []).map((n) => n.authorId)]);
  return toIncidentResponse(i, names);
}

/** An assignee must be a member of the same org; otherwise it is reported as not found. */
async function assertMember(orgId: Types.ObjectId, userId: string | null | undefined) {
  if (!userId) return;
  if (!(await Membership.exists({ orgId, userId }))) throw AppError.validation("Assignee is not a member of this organisation");
}

export function incidentRoutes(config: AppConfig): PolicyRouter {
  const r = new PolicyRouter(config);

  r.route(
    "get",
    "/incidents",
    "incidents:read",
    validate("query", listQuery),
    ah(async (req, res) => {
      const { orgId } = authOf(req);
      const q = parsed<z.infer<typeof listQuery>>(req, "query");
      const filter: Record<string, unknown> = { orgId };
      if (q.status) filter.status = q.status;
      if (q.priority) filter.priority = q.priority;
      const items = (await Incident.find(filter).sort({ updatedAt: -1 }).limit(q.limit).lean()) as IncidentDoc[];
      const names = await userNames(items.flatMap((i) => [i.assigneeId, ...(i.notes ?? []).map((n) => n.authorId)]));
      res.json({ items: items.map((i) => toIncidentResponse(i, names)) });
    }),
  );

  r.route(
    "get",
    "/incidents/:id",
    "incidents:read",
    validate("params", idParams),
    ah(async (req, res) => {
      const { id } = parsed<{ id: string }>(req, "params");
      const incident = await Incident.findOne({ orgId: authOf(req).orgId, _id: id }).lean();
      if (!incident) throw AppError.notFound("Incident");
      res.json(await respondWith(incident as IncidentDoc));
    }),
  );

  r.route(
    "post",
    "/incidents",
    "incidents:write",
    validate("body", createIncidentBodySchema),
    ah(async (req, res) => {
      const { orgId, userId } = authOf(req);
      const body = parsed<z.infer<typeof createIncidentBodySchema>>(req, "body");
      await assertMember(orgId, body.assigneeId);
      const incident = await Incident.create({ ...body, orgId, createdBy: userId });
      await auditFromRequest(req, "incident.create", { type: "incident", id: String(incident._id) }, { title: body.title });
      res.status(201).json(await respondWith(incident.toObject() as IncidentDoc));
    }),
  );

  r.route(
    "patch",
    "/incidents/:id",
    "incidents:write",
    validate("params", idParams),
    validate("body", updateIncidentBodySchema),
    ah(async (req, res) => {
      const { orgId } = authOf(req);
      const { id } = parsed<{ id: string }>(req, "params");
      const body = parsed<z.infer<typeof updateIncidentBodySchema>>(req, "body");
      await assertMember(orgId, body.assigneeId);
      const before = await Incident.findOne({ orgId, _id: id }).lean();
      if (!before) throw AppError.notFound("Incident");
      const incident = await Incident.findOneAndUpdate({ orgId, _id: id }, { $set: body }, { new: true, runValidators: true }).lean();
      if (!incident) throw AppError.notFound("Incident");
      const changes = Object.fromEntries(
        Object.keys(body).map((k) => [k, { from: (before as Record<string, unknown>)[k] ?? null, to: (body as Record<string, unknown>)[k] }]),
      );
      await auditFromRequest(req, "incident.update", { type: "incident", id }, { changes });
      res.json(await respondWith(incident as IncidentDoc));
    }),
  );

  r.route(
    "post",
    "/incidents/:id/notes",
    "incidents:write",
    validate("params", idParams),
    validate("body", incidentNoteBodySchema),
    ah(async (req, res) => {
      const { orgId, userId } = authOf(req);
      const { id } = parsed<{ id: string }>(req, "params");
      const { text } = parsed<{ text: string }>(req, "body");
      const incident = await Incident.findOneAndUpdate(
        { orgId, _id: id },
        { $push: { notes: { authorId: userId, text, createdAt: new Date() } } },
        { new: true },
      ).lean();
      if (!incident) throw AppError.notFound("Incident");
      await auditFromRequest(req, "incident.note", { type: "incident", id });
      res.status(201).json(await respondWith(incident as IncidentDoc));
    }),
  );

  r.route(
    "delete",
    "/incidents/:id",
    "incidents:delete",
    validate("params", idParams),
    ah(async (req, res) => {
      const { orgId } = authOf(req);
      const { id } = parsed<{ id: string }>(req, "params");
      const incident = await Incident.findOneAndDelete({ orgId, _id: id }).lean();
      if (!incident) throw AppError.notFound("Incident");
      await auditFromRequest(req, "incident.delete", { type: "incident", id }, { title: incident.title });
      res.status(204).end();
    }),
  );

  return r;
}
