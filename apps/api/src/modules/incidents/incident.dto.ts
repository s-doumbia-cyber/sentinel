import type { Types } from "mongoose";
import { User } from "../../models/identity.js";

/** Structural view of a lean incident (Mongoose lean types flatten subdocuments inconsistently). */
export interface LeanIncident {
  _id: Types.ObjectId;
  title: string;
  description?: string | null;
  attackType: string;
  status: string;
  priority: string;
  severity: string;
  sourceIp?: string | null;
  assigneeId?: Types.ObjectId | null;
  legacyAutoGenerated?: boolean | null;
  origin?: string | null;
  alertIds?: Types.ObjectId[] | null;
  entities?: { type?: string | null; value?: string | null; role?: string | null }[] | null;
  correlation?: { key?: string | null; windowMinutes?: number | null; basis?: string | null } | null;
  firstSeen?: Date | null;
  lastSeen?: Date | null;
  notes?: { authorId?: Types.ObjectId | null; text?: string | null; createdAt?: Date | null }[] | null;
  createdAt?: Date;
  updatedAt?: Date;
}

export async function userNames(ids: (Types.ObjectId | null | undefined)[]): Promise<Map<string, string>> {
  const unique = [...new Set(ids.filter(Boolean).map(String))];
  const users = unique.length ? await User.find({ _id: { $in: unique } }).select("name").lean() : [];
  return new Map(users.map((u) => [String(u._id), u.name]));
}

export function toIncidentResponse(i: LeanIncident, names: Map<string, string>) {
  return {
    id: String(i._id),
    title: i.title,
    description: i.description ?? "",
    attackType: i.attackType,
    status: i.status,
    priority: i.priority,
    severity: i.severity,
    sourceIp: i.sourceIp ?? null,
    assignee: i.assigneeId ? { id: String(i.assigneeId), name: names.get(String(i.assigneeId)) ?? "Former member" } : null,
    legacyAutoGenerated: i.legacyAutoGenerated ?? false,
    origin: i.origin ?? "manual",
    correlation: i.correlation?.basis ? { basis: i.correlation.basis, windowMinutes: i.correlation.windowMinutes ?? null } : null,
    alertCount: i.alertIds?.length ?? 0,
    entities: (i.entities ?? []).map((e) => ({ type: e.type ?? "ip", value: e.value ?? "", role: e.role ?? "source" })),
    firstSeen: i.firstSeen ?? null,
    lastSeen: i.lastSeen ?? null,
    notes: (i.notes ?? []).map((n) => ({
      authorId: n.authorId ? String(n.authorId) : null,
      authorName: n.authorId ? (names.get(String(n.authorId)) ?? "Former member") : null,
      text: n.text ?? "",
      createdAt: n.createdAt ?? null,
    })),
    createdAt: i.createdAt ?? null,
    updatedAt: i.updatedAt ?? null,
  };
}

export async function respondWith(i: LeanIncident) {
  const names = await userNames([i.assigneeId, ...(i.notes ?? []).map((n) => n.authorId)]);
  return toIncidentResponse(i, names);
}
