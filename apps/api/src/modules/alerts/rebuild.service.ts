import type { Types } from "mongoose";
import { AppError } from "../../lib/errors.js";
import type { Logger } from "../../lib/logger.js";
import { Alert, AuditLog, Flow, Incident, IncidentEvent } from "../../models/tenant.js";
import { writeAudit } from "../audit/audit.service.js";
import type { CorrelationService } from "../incidents/correlation.service.js";
import type { RuleService } from "../rules/rule.service.js";
import type { ScoringService } from "../scoring/scoring.service.js";
import { loadAlertPolicy } from "./policy.js";

export const REAPPLY_DONE = "detection.reapply_done";
export const REAPPLY_FAILED = "detection.reapply_failed";

/** Statuses only an analyst sets (new evidence never overwrites them). */
const ANALYST_ALERT_STATUSES = ["acknowledged", "dismissed", "resolved"];

export interface ReapplyPlan {
  /** Alerts nobody acted on: deleted and rebuilt from the stored evidence. */
  alertsRebuilt: number;
  /** Alerts an analyst triaged, or that sit in an incident an analyst worked on: left exactly as they are. */
  alertsKept: number;
  incidentsRebuilt: number;
  incidentsKept: number;
}

interface Classified {
  plan: ReapplyPlan;
  frozenAlertIds: Types.ObjectId[];
  frozenKeys: Set<string>;
  machineIncidentIds: Types.ObjectId[];
}

export interface ReapplyResult {
  plan: ReapplyPlan;
  after: { alerts: number; incidents: number; ruleAlertsCreated: number; modelAlertsCreated: number; suppressedVerdicts: { belowMinConfidence: number; allowlisted: number } };
  durationMs: number;
}

/**
 * Rebuilds one org's alerts and incidents from the verdicts and flows already
 * stored, under the org's current detection settings (minimum model confidence,
 * allowlist, review threshold, enabled rules). Flows and their verdicts are never
 * changed; only the "already folded into an alert" marks on malicious flows are
 * reset so the same evidence can be re-evaluated.
 *
 * What an analyst did is never discarded: an alert with a verdict or an
 * analyst-set status, an incident created or worked on by a person (not just
 * grouped by Sentinel), and every alert inside such an incident stay untouched,
 * and their evidence is not counted a second time. Everything else is machine
 * output and is rebuilt. Running it again with unchanged settings yields the
 * same alerts and incidents.
 */
/** Whether a queued or running job of this kind exists for the org (across API and worker processes). */
export type QueueBusy = (kind: "score" | "reapply", orgId: Types.ObjectId) => Promise<boolean>;

export class AlertRebuildService {
  /** Requests between their checks and the enqueue; the queue itself tracks the run after that. */
  private readonly starting = new Set<string>();

  constructor(
    private readonly scoring: ScoringService,
    private readonly rules: RuleService,
    private readonly correlation: CorrelationService,
    private readonly logger: Logger,
    private readonly busy: QueueBusy = async () => false,
  ) {}

  async isRunning(orgId: Types.ObjectId): Promise<boolean> {
    return this.starting.has(String(orgId)) || (await this.busy("reapply", orgId));
  }

  /**
   * Refuses while scoring or another rebuild is queued or running. The queue checks
   * are async; the final check-and-take is synchronous, so two quick requests cannot
   * both pass. Hold it until the job is enqueued, then `release()`.
   */
  async begin(orgId: Types.ObjectId): Promise<void> {
    const [scoringQueued, rebuildQueued] = await Promise.all([this.busy("score", orgId), this.busy("reapply", orgId)]);
    if (this.scoring.isRunning(orgId) || scoringQueued) throw AppError.conflict("Scoring is running for this organisation; try again when it has finished");
    if (this.starting.has(String(orgId)) || rebuildQueued) throw AppError.conflict("Alerts are already being rebuilt for this organisation");
    this.starting.add(String(orgId));
  }

  release(orgId: Types.ObjectId): void {
    this.starting.delete(String(orgId));
  }

  /** What a run would keep and what it would rebuild, without changing anything. */
  async plan(orgId: Types.ObjectId): Promise<ReapplyPlan> {
    return (await this.classify(orgId)).plan;
  }

  private async classify(orgId: Types.ObjectId): Promise<Classified> {
    const [incidents, humanEventIncidents, alerts] = await Promise.all([
      Incident.find({ orgId }).select("origin status assigneeId notes legacyAutoGenerated").lean(),
      IncidentEvent.find({ orgId, actorId: { $ne: null } }).distinct("incidentId"),
      Alert.find({ orgId }).select("verdict status incidentId dedupeKey").lean(),
    ]);
    const workedOn = new Set(humanEventIncidents.map(String));
    const keptIncidents = new Set(
      incidents
        .filter((i) => i.origin !== "correlated" || i.legacyAutoGenerated || i.status !== "Open" || i.assigneeId || (i.notes?.length ?? 0) > 0 || workedOn.has(String(i._id)))
        .map((i) => String(i._id)),
    );
    // An analyst decision on one alert protects its whole incident, so no kept incident loses members.
    for (const a of alerts) {
      if (a.incidentId && (a.verdict || ANALYST_ALERT_STATUSES.includes(a.status))) keptIncidents.add(String(a.incidentId));
    }
    const frozen = alerts.filter((a) => a.verdict || ANALYST_ALERT_STATUSES.includes(a.status) || (a.incidentId && keptIncidents.has(String(a.incidentId))));
    const machineIncidentIds = incidents.filter((i) => !keptIncidents.has(String(i._id))).map((i) => i._id);
    return {
      plan: { alertsRebuilt: alerts.length - frozen.length, alertsKept: frozen.length, incidentsRebuilt: machineIncidentIds.length, incidentsKept: incidents.length - machineIncidentIds.length },
      frozenAlertIds: frozen.map((a) => a._id),
      frozenKeys: new Set(frozen.map((a) => a.dedupeKey)),
      machineIncidentIds,
    };
  }

  /** Runs the rebuild (the "reapply" job body; `begin()` keeps a second one from being queued). */
  async rebuild(orgId: Types.ObjectId): Promise<ReapplyResult> {
    const started = Date.now();
    {
      const c = await this.classify(orgId);
      // Machine-made incidents: correlated and untouched. Their investigation-log events go with them.
      if (c.machineIncidentIds.length) {
        await IncidentEvent.deleteMany({ orgId, incidentId: { $in: c.machineIncidentIds } });
        await Incident.deleteMany({ orgId, _id: { $in: c.machineIncidentIds } });
      }
      await Alert.deleteMany({ orgId, _id: { $nin: c.frozenAlertIds } });
      // Re-open every malicious verdict for alerting; the verdicts themselves stay on the flows.
      await Flow.updateMany(
        { orgId, scoreStatus: "scored", "scored.label": { $ne: "Normal" }, alertedAt: { $ne: null } },
        { $set: { alertedAt: null, alertClaim: null, alertClaimedAt: null, alertSuppressed: null } },
      );

      const policy = { ...(await loadAlertPolicy(orgId)), frozenKeys: c.frozenKeys };
      const ruleRun = await this.rules.run(orgId, {}, policy);
      const modelAlertsCreated = await this.scoring.alertUnalerted(orgId, undefined, { policy });
      await this.correlation.correlate(orgId);

      const [alerts, incidents, belowMinConfidence, allowlisted] = await Promise.all([
        Alert.countDocuments({ orgId }),
        Incident.countDocuments({ orgId }),
        Flow.countDocuments({ orgId, alertSuppressed: "below_min_confidence" }),
        Flow.countDocuments({ orgId, alertSuppressed: "allowlisted" }),
      ]);
      return {
        plan: c.plan,
        after: { alerts, incidents, ruleAlertsCreated: ruleRun.created, modelAlertsCreated, suppressedVerdicts: { belowMinConfidence, allowlisted } },
        durationMs: Date.now() - started,
      };
    }
  }

  /** The job body: rebuild, then record the outcome in the audit log either way. */
  async runAudited(orgId: Types.ObjectId, actorId: Types.ObjectId): Promise<void> {
    try {
      const result = await this.rebuild(orgId);
      await writeAudit(null, { orgId, actorId, action: REAPPLY_DONE, target: { type: "org", id: String(orgId) }, meta: { ...result } });
      this.logger.info({ orgId: String(orgId), ...result.after }, "Alerts rebuilt under the current detection settings");
    } catch (err) {
      this.logger.error({ err, orgId: String(orgId) }, "Alert rebuild failed");
      await writeAudit(null, {
        orgId,
        actorId,
        action: REAPPLY_FAILED,
        target: { type: "org", id: String(orgId) },
        meta: { error: err instanceof Error ? err.message.slice(0, 300) : "unknown error" },
      });
    }
  }

  /** The most recent finished run (done or failed), read from the audit log. */
  async lastRun(orgId: Types.ObjectId) {
    const entry = await AuditLog.findOne({ orgId, action: { $in: [REAPPLY_DONE, REAPPLY_FAILED] } }).sort({ ts: -1, _id: -1 }).lean();
    if (!entry) return null;
    const meta = (entry.meta ?? {}) as Record<string, unknown>;
    return { at: entry.ts, status: entry.action === REAPPLY_DONE ? ("done" as const) : ("failed" as const), actorId: entry.actorId ? String(entry.actorId) : null, ...meta };
  }
}
