function LegacyNote({ incident }: { incident: Incident }) {
  if (!incident.legacyAutoGenerated) return null;
  return (
    <NeutralBadge className="bg-sev-medium/15 text-sevfg-medium" title="Created by the legacy backend from dataset labels, with an invented assignee and status. Review before relying on it.">
      legacy auto-generated
    </NeutralBadge>
  );
}

function CreateIncident({ open, onOpenChange }: { open: boolean; onOpenChange: (o: boolean) => void }) {
  const toast = useToast();
  const members = useMembers();
  const [form, setForm] = useState({ title: "", attackType: "PortScan", severity: "medium", priority: "P3", sourceIp: "", assigneeId: "", description: "" });
  const [errors, setErrors] = useState<Record<string, string>>({});
  const create = useOrgMutation((body: unknown) => api<Incident>("/incidents", { method: "POST", body }), ["incidents"]);
  const submit = (e: FormEvent) => {
    e.preventDefault();
    const body = {
      title: form.title,
      attackType: form.attackType,
      severity: form.severity,
      priority: form.priority,
      ...(form.sourceIp.trim() ? { sourceIp: form.sourceIp.trim() } : {}),
      ...(form.assigneeId ? { assigneeId: form.assigneeId } : {}),
      ...(form.description.trim() ? { description: form.description.trim() } : {}),
    };
    const parsed = createIncidentBodySchema.safeParse(body);
    if (!parsed.success) return setErrors(Object.fromEntries(parsed.error.issues.map((i) => [String(i.path[0]), i.message])));
    setErrors({});
    create.mutate(parsed.data, {
      onSuccess: () => {
        toast.success("Incident created");
        onOpenChange(false);
        setForm((f) => ({ ...f, title: "", sourceIp: "", description: "" }));
      },
      onError: (err) => toast.error(errorMessage(err)),
    });
  };
  const set = (k: keyof typeof form) => (e: { target: { value: string } }) => setForm((f) => ({ ...f, [k]: e.target.value }));
  return (
    <Dialog open={open} onOpenChange={onOpenChange} title="Create incident" description="Group what you are investigating. Correlation from alerts arrives in roadmap Phase 3.">
      <form id="create-incident" onSubmit={submit} className="space-y-4" noValidate>
        <Field label="Title" error={errors.title}>
          {({ id, describedBy, invalid }) => <Input id={id} value={form.title} onChange={set("title")} aria-describedby={describedBy} aria-invalid={invalid} />}
        </Field>
        <div className="grid grid-cols-2 gap-3">
          <Field label="Attack type">
            {({ id }) => (
              <Select id={id} value={form.attackType} onChange={set("attackType")}>
                {ATTACK_CLASSES.filter((c) => c !== "Normal").map((c) => (
                  <option key={c}>{c}</option>
                ))}
              </Select>
            )}
          </Field>
          <Field label="Severity">
            {({ id }) => (
              <Select id={id} value={form.severity} onChange={set("severity")}>
                {SEVERITIES.map((s) => (
                  <option key={s}>{s}</option>
                ))}
              </Select>
            )}
          </Field>
          <Field label="Priority">
            {({ id }) => (
              <Select id={id} value={form.priority} onChange={set("priority")}>
                {PRIORITIES.map((p) => (
                  <option key={p}>{p}</option>
                ))}
              </Select>
            )}
          </Field>
          <Field label="Assignee">
            {({ id }) => (
              <Select id={id} value={form.assigneeId} onChange={set("assigneeId")}>
                <option value="">Unassigned</option>
                {members.data?.items.map((m) => (
                  <option key={m.userId} value={m.userId}>
                    {m.name}
                  </option>
                ))}
              </Select>
            )}
          </Field>
        </div>
        <Field label="Source IP (optional)" error={errors.sourceIp}>
          {({ id, describedBy, invalid }) => <Input id={id} className="font-mono" value={form.sourceIp} onChange={set("sourceIp")} aria-describedby={describedBy} aria-invalid={invalid} />}
        </Field>
        <Field label="Description (optional)">
          {({ id }) => <Textarea id={id} value={form.description} onChange={set("description")} />}
        </Field>
        <div className="flex justify-end gap-2">
          <Button onClick={() => onOpenChange(false)}>Cancel</Button>
          <Button type="submit" variant="primary" loading={create.isPending}>
            Create incident
          </Button>
        </div>
      </form>
    </Dialog>
  );
}

export function IncidentsPage() {
  const { can } = useAuth();
  const incidents = useIncidents();
  const [params, setParams] = useSearchParams();
  const view = params.get("view") === "board" ? "board" : "table";
  const navigate = useNavigate();
  const toast = useToast();
  const move = useMoveIncident();
  const [creating, setCreating] = useState(false);
  const items = incidents.data?.items ?? [];
  const set = (k: string, v: string | null) => {
    const next = new URLSearchParams(params);
    if (v) next.set(k, v);
    else next.delete(k);
    setParams(next);
  };

  return (
    <>
      <PageHeader
        title="Incidents"
        description="What the team is investigating. Sentinel groups alerts from the same source within the correlation window; analysts can also open incidents from alerts or from scratch."
        actions={
          <>
            <div role="group" aria-label="View" className="flex rounded-md border p-0.5">
              {(["table", "board"] as const).map((v) => (
                <button key={v} type="button" aria-pressed={view === v} onClick={() => set("view", v === "table" ? null : v)} className={cn("flex h-8 items-center gap-1.5 rounded-sm px-2.5 text-small", view === v ? "bg-surface-3 text-fg-1" : "text-fg-2 hover:text-fg-1")}>
                  {v === "table" ? <Table2 aria-hidden className="h-4 w-4" /> : <LayoutGrid aria-hidden className="h-4 w-4" />}
                  {v === "table" ? "Table" : "Board"}
                </button>
              ))}
            </div>
            {can("incidents:write") && (
              <Button variant="primary" onClick={() => setCreating(true)}>
                <Plus aria-hidden className="h-4 w-4" /> Create incident
              </Button>
            )}
          </>
        }
      />
      {incidents.isLoading ? (
        <Card>
          <SkeletonRows />
        </Card>
      ) : incidents.isError ? (
        <Card>
          <ErrorState error={incidents.error} onRetry={() => void incidents.refetch()} />
        </Card>
      ) : items.length === 0 ? (
        <Card>
          <EmptyState title="No incidents" description="Create one when a set of flows deserves an investigation." />
        </Card>
      ) : view === "board" ? (
        <IncidentBoard
          items={items}
          canMove={can("incidents:write")}
          onOpen={(id) => navigate(`/incidents/${id}`)}
          onMove={(incident, to) =>
            move.mutate(
              { id: incident.id, status: to },
              {
                onSuccess: () => toast.success(`Moved to ${to}`),
                onError: (e) => toast.error(`Could not move “${incident.title}”: ${errorMessage(e)}. It is back in ${incident.status}.`),
              },
            )
          }
        />
      ) : (
        <Card aria-label="Incidents table" tabIndex={0} className="overflow-x-auto">
          <table className="w-full text-small">
            <caption className="sr-only">Incidents, most recently updated first</caption>
            <thead className="text-left text-caption uppercase tracking-[0.04em] text-fg-3">
              <tr className="border-b border-subtle">
                {["Priority", "Severity", "Title", "Alerts", "Status", "Assignee", "Updated"].map((h) => (
                  <th key={h} scope="col" className="px-4 py-2.5 font-medium">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {items.map((i) => (
                <tr key={i.id} tabIndex={0} onClick={() => navigate(`/incidents/${i.id}`)} onKeyDown={(e) => e.key === "Enter" && navigate(`/incidents/${i.id}`)} className="cursor-pointer border-b border-subtle last:border-0 hover:bg-surface-3/60 focus-visible:bg-surface-3">
                  <td className="px-4 py-row">
                    <NeutralBadge>{i.priority}</NeutralBadge>
                  </td>
                  <td className="px-4 py-row">
                    <SeverityBadge severity={i.severity} />
                  </td>
                  <td className="px-4 py-row text-fg-1">
                    <span className="flex flex-wrap items-center gap-2">
                      {i.title} <LegacyNote incident={i} />
                      {i.origin === "correlated" && <NeutralBadge className="border border-dashed" title={i.correlation?.basis}>grouped by Sentinel</NeutralBadge>}
                    </span>
                  </td>
                  <td className="tnum px-4 py-row text-fg-2">{i.alertCount}</td>
                  <td className="px-4 py-row text-fg-2">{i.status}</td>
                  <td className="px-4 py-row text-fg-2">{i.assignee?.name ?? "Unassigned"}</td>
                  <td className="whitespace-nowrap px-4 py-row text-fg-3" title={utcTitle(i.updatedAt)}>
                    {formatWhen(i.updatedAt)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>
      )}
      <CreateIncident open={creating} onOpenChange={setCreating} />
    </>
  );
}
