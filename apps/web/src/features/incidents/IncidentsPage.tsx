import { LayoutGrid, Plus, Table2, Trash2 } from "lucide-react";
import { useState, type FormEvent } from "react";
import { useSearchParams } from "react-router-dom";
import { ATTACK_CLASSES, INCIDENT_STATUSES, PRIORITIES, SEVERITIES, createIncidentBodySchema, type AttackClass, type Severity } from "@sentinel/shared";
import { MitreChip, NeutralBadge, SeverityBadge } from "@/components/ui/Badges";
import { Button } from "@/components/ui/Button";
import { Card, PageHeader } from "@/components/ui/Card";
import { DefinitionList, EntityChip } from "@/components/ui/Data";
import { Field, Input, Select, Textarea } from "@/components/ui/Form";
import { ConfirmDialog, Dialog, Drawer } from "@/components/ui/Overlays";
import { EmptyState, ErrorState, SkeletonRows } from "@/components/ui/States";
import { useToast } from "@/components/ui/Toast";
import { useAuth } from "@/features/auth/AuthContext";
import { api, errorMessage } from "@/lib/api";
import { cn, formatDateTime, formatWhen, utcTitle } from "@/lib/format";
import { useIncidents, useMembers, useOrgMutation } from "@/lib/queries";
import type { Incident, IncidentStatus, Priority } from "@/lib/types";

type Patch = Partial<{ status: IncidentStatus; priority: Priority; severity: Severity; assigneeId: string | null; title: string }>;

function usePatch() {
  return useOrgMutation(({ id, patch }: { id: string; patch: Patch }) => api<Incident>(`/incidents/${id}`, { method: "PATCH", body: patch }), ["incidents"]);
}

function LegacyNote({ incident }: { incident: Incident }) {
  if (!incident.legacyAutoGenerated) return null;
  return (
    <NeutralBadge className="bg-sev-medium/15 text-sevfg-medium" title="Created by the legacy backend from dataset labels, with an invented assignee and status. Review before relying on it.">
      legacy auto-generated
    </NeutralBadge>
  );
}

function CreateIncident({ open, onOpenChange }: { open: boolean; onOpenChange: (o: boolean) => void }) {
  const toast = useToast();
  const members = useMembers();
  const [form, setForm] = useState({ title: "", attackType: "PortScan", severity: "medium", priority: "P3", sourceIp: "", assigneeId: "", description: "" });
  const [errors, setErrors] = useState<Record<string, string>>({});
  const create = useOrgMutation((body: unknown) => api<Incident>("/incidents", { method: "POST", body }), ["incidents"]);
  const submit = (e: FormEvent) => {
    e.preventDefault();
    const body = {
      title: form.title,
      attackType: form.attackType,
      severity: form.severity,
      priority: form.priority,
      ...(form.sourceIp.trim() ? { sourceIp: form.sourceIp.trim() } : {}),
      ...(form.assigneeId ? { assigneeId: form.assigneeId } : {}),
      ...(form.description.trim() ? { description: form.description.trim() } : {}),
    };
    const parsed = createIncidentBodySchema.safeParse(body);
    if (!parsed.success) return setErrors(Object.fromEntries(parsed.error.issues.map((i) => [String(i.path[0]), i.message])));
    setErrors({});
    create.mutate(parsed.data, {
      onSuccess: () => {
        toast.success("Incident created");
        onOpenChange(false);
        setForm((f) => ({ ...f, title: "", sourceIp: "", description: "" }));
      },
      onError: (err) => toast.error(errorMessage(err)),
    });
  };
  const set = (k: keyof typeof form) => (e: { target: { value: string } }) => setForm((f) => ({ ...f, [k]: e.target.value }));
  return (
    <Dialog open={open} onOpenChange={onOpenChange} title="Create incident" description="Group what you are investigating. Correlation from alerts arrives in roadmap Phase 3.">
      <form id="create-incident" onSubmit={submit} className="space-y-4" noValidate>
        <Field label="Title" error={errors.title}>
          {({ id, describedBy, invalid }) => <Input id={id} value={form.title} onChange={set("title")} aria-describedby={describedBy} aria-invalid={invalid} />}
        </Field>
        <div className="grid grid-cols-2 gap-3">
          <Field label="Attack type">
            {({ id }) => (
              <Select id={id} value={form.attackType} onChange={set("attackType")}>
                {ATTACK_CLASSES.filter((c) => c !== "Normal").map((c) => (
                  <option key={c}>{c}</option>
                ))}
              </Select>
            )}
          </Field>
          <Field label="Severity">
            {({ id }) => (
              <Select id={id} value={form.severity} onChange={set("severity")}>
                {SEVERITIES.map((s) => (
                  <option key={s}>{s}</option>
                ))}
              </Select>
            )}
          </Field>
          <Field label="Priority">
            {({ id }) => (
              <Select id={id} value={form.priority} onChange={set("priority")}>
                {PRIORITIES.map((p) => (
                  <option key={p}>{p}</option>
                ))}
              </Select>
            )}
          </Field>
          <Field label="Assignee">
            {({ id }) => (
              <Select id={id} value={form.assigneeId} onChange={set("assigneeId")}>
                <option value="">Unassigned</option>
                {members.data?.items.map((m) => (
                  <option key={m.userId} value={m.userId}>
                    {m.name}
                  </option>
                ))}
              </Select>
            )}
          </Field>
        </div>
        <Field label="Source IP (optional)" error={errors.sourceIp}>
          {({ id, describedBy, invalid }) => <Input id={id} className="font-mono" value={form.sourceIp} onChange={set("sourceIp")} aria-describedby={describedBy} aria-invalid={invalid} />}
        </Field>
        <Field label="Description (optional)">
          {({ id }) => <Textarea id={id} value={form.description} onChange={set("description")} />}
        </Field>
        <div className="flex justify-end gap-2">
          <Button onClick={() => onOpenChange(false)}>Cancel</Button>
          <Button type="submit" variant="primary" loading={create.isPending}>
            Create incident
          </Button>
        </div>
      </form>
    </Dialog>
  );
}

function IncidentDrawer({ incident, onClose }: { incident: Incident | null; onClose: () => void }) {
  const { can } = useAuth();
  const toast = useToast();
  const members = useMembers();
  const patch = usePatch();
  const [note, setNote] = useState("");
  const [confirmDelete, setConfirmDelete] = useState(false);
  const addNote = useOrgMutation(({ id, text }: { id: string; text: string }) => api<Incident>(`/incidents/${id}/notes`, { method: "POST", body: { text } }), ["incidents"]);
  const del = useOrgMutation((id: string) => api(`/incidents/${id}`, { method: "DELETE" }), ["incidents"]);
  const writable = can("incidents:write");
  if (!incident) return <Drawer open={false} onOpenChange={() => undefined} title="Incident">{null}</Drawer>;
  const change = (p: Patch) => patch.mutate({ id: incident.id, patch: p }, { onError: (e) => toast.error(errorMessage(e)) });
  return (
    <Drawer open onOpenChange={(o) => !o && onClose()} title={incident.title} subtitle={`Updated ${formatWhen(incident.updatedAt)}`}>
      <div className="mb-5 flex flex-wrap gap-2">
        <SeverityBadge severity={incident.severity} />
        <NeutralBadge>{incident.priority}</NeutralBadge>
        <MitreChip cls={incident.attackType as AttackClass} />
        <LegacyNote incident={incident} />
      </div>
      <div className="mb-6 grid grid-cols-1 gap-3 sm:grid-cols-3">
        <label className="text-caption text-fg-3">
          Status
          <Select className="mt-1" disabled={!writable || patch.isPending} value={incident.status} onChange={(e) => change({ status: e.target.value as IncidentStatus })}>
            {INCIDENT_STATUSES.map((s) => (
              <option key={s}>{s}</option>
            ))}
          </Select>
        </label>
        <label className="text-caption text-fg-3">
          Priority
          <Select className="mt-1" disabled={!writable || patch.isPending} value={incident.priority} onChange={(e) => change({ priority: e.target.value as Priority })}>
            {PRIORITIES.map((p) => (
              <option key={p}>{p}</option>
            ))}
          </Select>
        </label>
        <label className="text-caption text-fg-3">
          Assignee
          <Select className="mt-1" disabled={!writable || patch.isPending} value={incident.assignee?.id ?? ""} onChange={(e) => change({ assigneeId: e.target.value || null })}>
            <option value="">Unassigned</option>
            {members.data?.items.map((m) => (
              <option key={m.userId} value={m.userId}>
                {m.name}
              </option>
            ))}
          </Select>
        </label>
      </div>
      <DefinitionList
        items={[
          ["Attack type", incident.attackType],
          ["Source IP", incident.sourceIp ? <EntityChip value={incident.sourceIp} /> : "—"],
          ["Created", <span title={utcTitle(incident.createdAt)}>{formatDateTime(incident.createdAt)}</span>],
        ]}
      />
      {incident.description && <p className="mt-4 whitespace-pre-wrap text-small text-fg-2">{incident.description}</p>}
      <section className="mt-6">
        <h3 className="mb-3 text-caption font-medium uppercase tracking-[0.04em] text-fg-3">Notes</h3>
        {incident.notes.length === 0 ? (
          <p className="text-small text-fg-3">No notes yet.</p>
        ) : (
          <ol className="space-y-3">
            {incident.notes.map((n, i) => (
              <li key={i} className="rounded-md border border-subtle p-3">
                <p className="text-caption text-fg-3" title={utcTitle(n.createdAt)}>
                  {n.authorName ?? "Unknown"} · {formatWhen(n.createdAt)}
                </p>
                <p className="mt-1 whitespace-pre-wrap text-small text-fg-1">{n.text}</p>
              </li>
            ))}
          </ol>
        )}
        {writable && (
          <form
            className="mt-3 space-y-2"
            onSubmit={(e) => {
              e.preventDefault();
              if (!note.trim()) return;
              addNote.mutate({ id: incident.id, text: note.trim() }, { onSuccess: () => setNote(""), onError: (err) => toast.error(errorMessage(err)) });
            }}
          >
            <label htmlFor="note" className="sr-only">
              Add a note
            </label>
            <Textarea id="note" placeholder="Add a note…" value={note} onChange={(e) => setNote(e.target.value)} />
            <div className="flex justify-between">
              <Button type="submit" size="sm" loading={addNote.isPending} disabled={!note.trim()}>
                Add note
              </Button>
              {can("incidents:delete") && (
                <Button size="sm" variant="ghost" onClick={() => setConfirmDelete(true)}>
                  <Trash2 aria-hidden className="h-4 w-4" /> Delete incident
                </Button>
              )}
            </div>
          </form>
        )}
      </section>
      <ConfirmDialog
        open={confirmDelete}
        onOpenChange={setConfirmDelete}
        title="Delete this incident?"
        consequence="The incident and its notes are permanently removed. The audit log keeps a record of the deletion."
        confirmLabel="Delete incident"
        loading={del.isPending}
        onConfirm={() =>
          del.mutate(incident.id, {
            onSuccess: () => {
              setConfirmDelete(false);
              onClose();
              toast.success("Incident deleted");
            },
            onError: (e) => toast.error(errorMessage(e)),
          })
        }
      />
    </Drawer>
  );
}

function Board({ items, onOpen }: { items: Incident[]; onOpen: (id: string) => void }) {
  return (
    <div className="grid gap-4 overflow-x-auto md:grid-cols-5">
      {INCIDENT_STATUSES.map((status) => {
        const col = items.filter((i) => i.status === status);
        return (
          <section key={status} aria-label={`${status} (${col.length})`} className="min-w-[220px] rounded-lg border border-subtle bg-bg-0 p-2">
            <h2 className="flex items-center justify-between px-2 py-1.5 text-caption font-medium uppercase tracking-[0.04em] text-fg-3">
              {status} <span className="tnum">{col.length}</span>
            </h2>
            <ul className="space-y-2">
              {col.map((i) => (
                <li key={i.id}>
                  <button type="button" onClick={() => onOpen(i.id)} className="w-full rounded-md border bg-surface-1 p-3 text-left shadow-e1 hover:border-strong">
                    <span className="flex flex-wrap gap-1">
                      <NeutralBadge>{i.priority}</NeutralBadge>
                      <SeverityBadge severity={i.severity} />
                    </span>
                    <span className="mt-2 line-clamp-2 block text-small font-medium text-fg-1">{i.title}</span>
                    <span className="mt-1 block text-caption text-fg-3">{i.assignee?.name ?? "Unassigned"}</span>
                  </button>
                </li>
              ))}
            </ul>
          </section>
        );
      })}
    </div>
  );
}

export function IncidentsPage() {
  const { can } = useAuth();
  const incidents = useIncidents();
  const [params, setParams] = useSearchParams();
  const view = params.get("view") === "board" ? "board" : "table";
  const selectedId = params.get("incident");
  const [creating, setCreating] = useState(false);
  const items = incidents.data?.items ?? [];
  const selected = items.find((i) => i.id === selectedId) ?? null;
  const set = (k: string, v: string | null) => {
    const next = new URLSearchParams(params);
    if (v) next.set(k, v);
    else next.delete(k);
    setParams(next);
  };

  return (
    <>
      <PageHeader
        title="Incidents"
        description="What the team is investigating. Incidents are created by analysts; automatic correlation is not built yet."
        actions={
          <>
            <div role="group" aria-label="View" className="flex rounded-md border p-0.5">
              {(["table", "board"] as const).map((v) => (
                <button key={v} type="button" aria-pressed={view === v} onClick={() => set("view", v === "table" ? null : v)} className={cn("flex h-8 items-center gap-1.5 rounded-sm px-2.5 text-small", view === v ? "bg-surface-3 text-fg-1" : "text-fg-2 hover:text-fg-1")}>
                  {v === "table" ? <Table2 aria-hidden className="h-4 w-4" /> : <LayoutGrid aria-hidden className="h-4 w-4" />}
                  {v === "table" ? "Table" : "Board"}
                </button>
              ))}
            </div>
            {can("incidents:write") && (
              <Button variant="primary" onClick={() => setCreating(true)}>
                <Plus aria-hidden className="h-4 w-4" /> Create incident
              </Button>
            )}
          </>
        }
      />
      {incidents.isLoading ? (
        <Card>
          <SkeletonRows />
        </Card>
      ) : incidents.isError ? (
        <Card>
          <ErrorState error={incidents.error} onRetry={() => void incidents.refetch()} />
        </Card>
      ) : items.length === 0 ? (
        <Card>
          <EmptyState title="No incidents" description="Create one when a set of flows deserves an investigation." />
        </Card>
      ) : view === "board" ? (
        <Board items={items} onOpen={(id) => set("incident", id)} />
      ) : (
        <Card className="overflow-x-auto">
          <table className="w-full text-small">
            <caption className="sr-only">Incidents, most recently updated first</caption>
            <thead className="text-left text-caption uppercase tracking-[0.04em] text-fg-3">
              <tr className="border-b border-subtle">
                {["Priority", "Severity", "Title", "Status", "Assignee", "Updated"].map((h) => (
                  <th key={h} scope="col" className="px-4 py-2.5 font-medium">
                    {h}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {items.map((i) => (
                <tr key={i.id} tabIndex={0} onClick={() => set("incident", i.id)} onKeyDown={(e) => e.key === "Enter" && set("incident", i.id)} className="cursor-pointer border-b border-subtle last:border-0 hover:bg-surface-3/60 focus-visible:bg-surface-3">
                  <td className="px-4 py-row">
                    <NeutralBadge>{i.priority}</NeutralBadge>
                  </td>
                  <td className="px-4 py-row">
                    <SeverityBadge severity={i.severity} />
                  </td>
                  <td className="px-4 py-row text-fg-1">
                    <span className="flex flex-wrap items-center gap-2">
                      {i.title} <LegacyNote incident={i} />
                    </span>
                  </td>
                  <td className="px-4 py-row text-fg-2">{i.status}</td>
                  <td className="px-4 py-row text-fg-2">{i.assignee?.name ?? "Unassigned"}</td>
                  <td className="whitespace-nowrap px-4 py-row text-fg-3" title={utcTitle(i.updatedAt)}>
                    {formatWhen(i.updatedAt)}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>
      )}
      <CreateIncident open={creating} onOpenChange={setCreating} />
      <IncidentDrawer incident={selected} onClose={() => set("incident", null)} />
    </>
  );
}
